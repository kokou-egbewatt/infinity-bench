"""The three animated result figures for section 11, drawn from data/gha-runners/.

    python3 site/scripts/figures/runners/build.py

Unlike the four scene figures (gen.py, equal phases), these run on free timings
in seconds, because the pickup figure plays in real time: one second on the
clock is one second on the fleet. Re-run build.py whenever the CSVs change;
each component records the data it was drawn from in a comment.
"""
import collections, csv, hashlib, os, statistics

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.normpath(os.path.join(HERE, '..', '..', '..', '..', 'data', 'gha-runners'))
AC, WARN, TX, TX2, TX3, HI, LINE, LINE2 = '#5eead4', '#e5b567', '#d6d6da', '#9c9ca4', '#67676f', '#f4f4f5', '#222328', '#2c2d33'
VW = 560

def rows(f):
    return list(csv.DictReader(open(os.path.join(DATA, f))))

def digest(*files):
    h = hashlib.sha256()
    for f in files:
        h.update(open(os.path.join(DATA, f), 'rb').read())
    return h.hexdigest()[:12]

# ---------------------------------------------------------------- plumbing

def P(t, dur):
    return f'{max(0.0, min(100.0, t / dur * 100)):.2f}%'

def show(name, a, b, dur, fade=0.3):
    """Opacity 1 between a and b seconds, fading over `fade`."""
    a1, b1 = min(a + fade, b), max(b - fade, a)
    return f'@keyframes {name}{{0%,{P(a,dur)}{{opacity:0}}{P(a1,dur)},{P(b1,dur)}{{opacity:1}}{P(b,dur)},100%{{opacity:0}}}}'

def grow(name, a, b, dur, hold_to, origin_x):
    """scaleX from 0 to 1 between a and b, held to hold_to, then back to 0."""
    return (f'@keyframes {name}{{0%,{P(a,dur)}{{transform:scaleX(0)}}{P(b,dur)},{P(hold_to,dur)}{{transform:scaleX(1)}}'
            f'{P(hold_to+0.5,dur)},100%{{transform:scaleX(0)}}}}')

def component(path, *, pfx, aria, dur, freeze, vw, vh, svg, caps, css, source, legend=''):
    """caps: list of (start, end, html). The progress ticks follow the captions."""
    cap_html, kf = [], []
    for i, (a, b, c) in enumerate(caps):
        nm = f'{pfx}-cap{i}'
        kf.append(show(nm, a, b, dur, fade=0.25))
        cap_html.append(f'<p style="animation:{nm} var(--dur) linear infinite" set:html={{{c!r}}} />')
    ticks = ''.join(f'<span style="flex:{(b - a):.2f}"></span>' for a, b, _ in caps)
    out = f"""---
// Generated by site/scripts/figures/runners/build.py from data/gha-runners ({source}). Edit results.py, not here.
---

<figure class="fig res" data-fig style="--dur:{dur}s; --freeze:-{freeze}s">
  <div class="draw"><svg viewBox="0 0 {vw} {vh}" role="img" aria-label={{{aria!r}}}>
{svg}
  </svg></div>
  <figcaption>{legend}
    <div class="caps">{''.join(cap_html)}</div>
    <div class="figbar">
      <div class="track"><i></i><div class="ticks">{ticks}</div></div>
      <span class="ctl"><button type="button" data-pp>pause</button> <button type="button" data-rp>replay</button></span>
    </div>
  </figcaption>
</figure>

<style is:global>
{chr(10).join(kf + css)}
</style>
"""
    with open(path, 'w') as f:
        f.write(out)

def key(items):
    """A legend row under the drawing: (swatch html, label) pairs."""
    return '<div class="key">' + ''.join(f'<span>{sw}{lab}</span>' for sw, lab in items) + '</div>'

SW_FILL = lambda c: f'<i style="background:{c}"></i>'
SW_DASH = lambda c: f'<i style="border:1px dashed {c}"></i>'
SW_BOX = lambda c: f'<i style="border:1.5px solid {c};border-radius:3px"></i>'

